-- Query 1: Complete 5-Table Join (Order Summary with Customer, Product, Employee, and Payment)
SELECT 
  O.BOOKING_ID,
  O.ORDER_DATE,
  C.NAME AS CUSTOMER_NAME,
  P.PRODUCT_NAME,
  P.PRICE AS UNIT_PRICE,
  O.QUANTITY,
  O.TOTAL_AMOUNT,
  E.EMPLOYEE_NAME AS SALES_REP,
  E.DEPARTMENT,
  PAY.PAYMENT_METHOD,
  PAY.PAYMENT_STATUS
FROM ORDERS O
JOIN CUSTOMER C ON O.CUSTOMER_ID = C.CUSTOMER_ID
JOIN PRODUCT P ON O.PRODUCT_ID = P.PRODUCT_ID
JOIN EMPLOYEE E ON O.EMPLOYEE_ID = E.EMPLOYEE_ID
JOIN PAYMENT PAY ON O.PAYMENT_ID = PAY.PAYMENT_ID;

-- Query 2: Support Tickets with Customer Contact Information
SELECT 
  S.TICKET_ID,
  S.ISSUE,
  S.STATUS,
  S.OPEN_DATE,
  C.NAME AS CUSTOMER_NAME,
  C.PHONE,
  C.EMAIL
FROM SUPPORT S
JOIN CUSTOMER C ON S.CUSTOMER_ID = C.CUSTOMER_ID;
