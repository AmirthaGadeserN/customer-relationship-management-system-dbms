-- ----------------------------------------------------------------------
-- 1. DROP EXISTING TABLES (Reverse Order of Dependencies)
-- ----------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE ORDERS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE SUPPORT CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE PAYMENT CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE PRODUCT CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE EMPLOYEE CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE CUSTOMER CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- ----------------------------------------------------------------------
-- 2. CREATE MASTER TABLES
-- ----------------------------------------------------------------------

-- TABLE 1: CUSTOMER
CREATE TABLE CUSTOMER (
  CUSTOMER_ID NUMBER PRIMARY KEY,
  NAME VARCHAR2(30),
  PHONE VARCHAR2(15),
  EMAIL VARCHAR2(50),
  ADDRESS VARCHAR2(50)
);

-- TABLE 2: EMPLOYEE
CREATE TABLE EMPLOYEE (
  EMPLOYEE_ID NUMBER PRIMARY KEY,
  EMPLOYEE_NAME VARCHAR2(50),
  DEPARTMENT VARCHAR2(50),
  PHONE VARCHAR2(15),
  EMAIL VARCHAR2(50)
);

-- TABLE 3: PRODUCT
CREATE TABLE PRODUCT (
  PRODUCT_ID NUMBER PRIMARY KEY,
  PRODUCT_NAME VARCHAR2(30),
  CATEGORY VARCHAR2(30),
  PRICE NUMBER(10,2),
  STOCK NUMBER
);

-- TABLE 4: PAYMENT
CREATE TABLE PAYMENT (
  PAYMENT_ID NUMBER PRIMARY KEY,
  AMOUNT NUMBER(10,2),
  PAYMENT_DATE DATE,
  PAYMENT_METHOD VARCHAR2(30),
  PAYMENT_STATUS VARCHAR2(30)
);

-- ----------------------------------------------------------------------
-- 3. CREATE TRANSACTION & RELATION TABLES (WITH FOREIGN KEYS)
-- ----------------------------------------------------------------------

-- TABLE 5: ORDERS (Central Booking Hub)
CREATE TABLE ORDERS (
  BOOKING_ID NUMBER PRIMARY KEY,
  ORDER_DATE DATE,
  QUANTITY NUMBER,
  TOTAL_AMOUNT NUMBER(10,2),
  CUSTOMER_ID NUMBER,
  EMPLOYEE_ID NUMBER,
  PRODUCT_ID NUMBER,
  PAYMENT_ID NUMBER,
  FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
  FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
  FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT(PAYMENT_ID)
);

-- TABLE 6: SUPPORT (Customer Issue Tracking)
CREATE TABLE SUPPORT (
  TICKET_ID NUMBER PRIMARY KEY,
  ISSUE VARCHAR2(100),
  STATUS VARCHAR2(30),
  OPEN_DATE DATE,
  CUSTOMER_ID NUMBER,
  FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);

